yc = set()

for x in range(1, 25):
    n1 = (
        8 * 25**6
        + 10 * 25**5
        + 15 * 25**4
        + 7 * 25**3
        + x * 25**2
        + 1 * 25**1
        + 1 * 25**0
    )

    n2 = x * 25**4 + 13 * 25**3 + 10 * 25**2 + 8 * 25**1 + 7 * 25**0

    r = n1 + n2

    for y in range(1, 101):
        if r % y == 0:
            yc.add(y)

print(len(yc))
